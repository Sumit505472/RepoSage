class RepositoryIngestionError(Exception):
    def __init__(self, status_code: int, detail: str) -> None:
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


@dataclass(frozen=True)
class RepositoryReference:
    owner: str
    name: str


@dataclass(frozen=True)
class TreeFile:
    path: str
    sha: str
    size: int


def parse_repository_url(repository_url: str) -> RepositoryReference:
    if (
        len(repository_url) > 2048
        or repository_url != repository_url.strip()
        or any(ord(character) < 32 for character in repository_url)
        or "\\" in repository_url
        or "%" in repository_url
    ):
        raise RepositoryIngestionError(422, "Invalid GitHub repository URL")

    try:
        parsed = urlsplit(repository_url)
        hostname = parsed.hostname
        port = parsed.port
    except ValueError as error:
        raise RepositoryIngestionError(
            422, "Invalid GitHub repository URL"
        ) from error

    if (
        parsed.scheme != "https"
        or hostname != "github.com"
        or parsed.username is not None
        or parsed.password is not None
        or port is not None
        or parsed.query
        or parsed.fragment
    ):
        raise RepositoryIngestionError(422, "Invalid GitHub repository URL")

    parts = parsed.path.strip("/").split("/")
    if len(parts) != 2:
        raise RepositoryIngestionError(422, "Invalid GitHub repository URL")

    owner, name = parts
    if name.lower().endswith(".git"):
        name = name[:-4]
    if (
        not OWNER_PATTERN.fullmatch(owner)
        or not REPOSITORY_PATTERN.fullmatch(name)
        or name in {".", ".."}
    ):
        raise RepositoryIngestionError(422, "Invalid GitHub repository URL")

    return RepositoryReference(owner=owner, name=name)


def should_include_file(path: str) -> bool:
    path_parts = path.split("/")
    if any(part.lower() in EXCLUDED_DIRECTORIES for part in path_parts[:-1]):
        return False

    filename = path_parts[-1].lower()
    if (
        filename.startswith(".env")
        or filename in EXCLUDED_FILENAMES
        or any(fnmatch(filename, pattern) for pattern in EXCLUDED_PATTERNS)
    ):
        return False

    suffix = "." + filename.rsplit(".", 1)[-1] if "." in filename else ""
    return suffix not in EXCLUDED_EXTENSIONS


class GitHubRepositoryIndexer:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings

    async def index(
        self,
        repository_url: str,
        client: httpx.AsyncClient,
    ) -> RepositoryIndexResponse:
        reference = parse_repository_url(repository_url)
        repository_api_path = (
            f"/repos/{quote(reference.owner, safe='')}/"
            f"{quote(reference.name, safe='')}"
        )

        metadata = await self._get_json(client, repository_api_path)
        if metadata.get("private") is True:
            raise RepositoryIngestionError(
                404, "Public repository not found"
            )
        if not isinstance(metadata.get("private"), bool):
            raise RepositoryIngestionError(
                502, "GitHub returned invalid repository metadata"
            )
        owner_metadata = metadata.get("owner")
        owner = (
            owner_metadata.get("login")
            if isinstance(owner_metadata, dict)
            else None
        )
        name = metadata.get("name")
        branch = metadata.get("default_branch")
        if not all(isinstance(value, str) and value for value in (owner, name, branch)):
            raise RepositoryIngestionError(
                502, "GitHub returned invalid repository metadata"
            )

        commit_path = (
            f"{repository_api_path}/commits/{quote(branch, safe='')}"
        )
        commit = await self._get_json(client, commit_path)
        commit_metadata = commit.get("commit")
        tree_metadata = (
            commit_metadata.get("tree")
            if isinstance(commit_metadata, dict)
            else None
        )
        tree_sha = (
            tree_metadata.get("sha")
            if isinstance(tree_metadata, dict)
            else None
        )
        if not isinstance(tree_sha, str) or not tree_sha:
            raise RepositoryIngestionError(
                502, "GitHub returned invalid commit metadata"
            )

        tree_files = await self._list_tree_files(
            client, repository_api_path, tree_sha
        )
        tree_files = [
            tree_file
            for tree_file in tree_files
            if tree_file.size <= self.settings.max_file_size_bytes
        ]
        if len(tree_files) > self.settings.max_repository_files:
            raise RepositoryIngestionError(
                413, "Repository exceeds the configured source file limit"
            )

        indexed_files: list[IndexedFile] = []
        total_source_bytes = 0
        for tree_file in tree_files:
            if total_source_bytes + tree_file.size > self.settings.max_total_source_bytes:
                raise RepositoryIngestionError(
                    413, "Repository exceeds the configured source size limit"
                )

            blob = await self._get_json(
                client,
                f"{repository_api_path}/git/blobs/"
                f"{quote(tree_file.sha, safe='')}",
            )
            source_bytes = self._decode_blob(blob, tree_file.size)
            if b"\x00" in source_bytes:
                continue
            try:
                source = source_bytes.decode("utf-8")
            except UnicodeDecodeError:
                continue

            total_source_bytes += len(source_bytes)
            extension = "." + tree_file.path.rsplit(".", 1)[-1].lower() \
                if "." in tree_file.path.rsplit("/", 1)[-1] else ""
            indexed_files.append(
                IndexedFile(
                    path=tree_file.path,
                    language=LANGUAGES_BY_EXTENSION.get(extension),
                    source=source,
                )
            )

        return RepositoryIndexResponse(
            owner=owner,
            name=name,
            branch=branch,
            files=indexed_files,
        )

    async def _list_tree_files(
        self,
        client: httpx.AsyncClient,
        repository_api_path: str,
        tree_sha: str,
    ) -> list[TreeFile]:
        tree_payload = await self._get_tree_pages(
            client,
            f"{repository_api_path}/git/trees/{quote(tree_sha, safe='')}?recursive=1",
        )
        if not tree_payload["truncated"]:
            return self._parse_tree_entries(tree_payload["tree"])

        collected: list[TreeFile] = []
        pending: list[tuple[str, str, int]] = [(tree_sha, "", 0)]
        visited_entries = 0
        while pending:
            current_sha, prefix, depth = pending.pop()
            if depth > MAX_TREE_DEPTH:
                raise RepositoryIngestionError(
                    413, "Repository directory nesting exceeds the limit"
                )
            payload = await self._get_tree_pages(
                client,
                f"{repository_api_path}/git/trees/"
                f"{quote(current_sha, safe='')}",
            )
            for entry in payload["tree"]:
                visited_entries += 1
                if visited_entries > MAX_TREE_ENTRIES:
                    raise RepositoryIngestionError(
                        413, "Repository tree exceeds the configured limit"
                    )
                relative_path = entry.get("path")
                entry_sha = entry.get("sha")
                if not isinstance(relative_path, str) or not relative_path:
                    raise RepositoryIngestionError(
                        502, "GitHub returned invalid repository tree entries"
                    )
                path = f"{prefix}/{relative_path}".lstrip("/")
                if entry.get("type") == "tree":
                    if not isinstance(entry_sha, str) or not entry_sha:
                        raise RepositoryIngestionError(
                            502, "GitHub returned invalid repository tree entries"
                        )
                    pending.append((entry_sha, path, depth + 1))
                elif entry.get("type") == "blob" and should_include_file(path):
                    collected.extend(self._parse_tree_entries([entry], prefix))
        return collected

    async def _get_tree_pages(
        self,
        client: httpx.AsyncClient,
        initial_url: str,
    ) -> dict[str, object]:
        url = f"{GITHUB_API_URL}{initial_url}"
        entries: list[dict[str, object]] = []
        truncated = False
        pages = 0
        while url:
            pages += 1
            if pages > MAX_TREE_PAGES:
                raise RepositoryIngestionError(
                    502, "GitHub returned too many repository tree pages"
                )
            response, payload = await self._get_response_json(client, url)
            page_entries = payload.get("tree")
            if not isinstance(page_entries, list):
                raise RepositoryIngestionError(
                    502, "GitHub returned an invalid repository tree"
                )
            if not isinstance(payload.get("truncated", False), bool):
                raise RepositoryIngestionError(
                    502, "GitHub returned an invalid repository tree"
                )
            if any(not isinstance(entry, dict) for entry in page_entries):
                raise RepositoryIngestionError(
                    502, "GitHub returned invalid repository tree entries"
                )
            entries.extend(page_entries)
            if len(entries) > MAX_TREE_ENTRIES:
                raise RepositoryIngestionError(
                    413, "Repository tree exceeds the configured limit"
                )
            truncated = truncated or payload.get("truncated") is True
            next_url = response.links.get("next", {}).get("url")
            if next_url:
                parsed_next = urlsplit(next_url)
                if parsed_next.scheme != "https" or parsed_next.netloc != "api.github.com":
                    raise RepositoryIngestionError(
                        502, "GitHub returned an unsafe pagination link"
                    )
                url = next_url
            else:
                url = ""
        return {"tree": entries, "truncated": truncated}

    @staticmethod
    def _parse_tree_entries(
        entries: list[dict[str, object]],
        prefix: str = "",
    ) -> list[TreeFile]:
        files: list[TreeFile] = []
        for entry in entries:
            if entry.get("type") != "blob":
                continue
            path = entry.get("path")
            sha = entry.get("sha")
            size = entry.get("size")
            if (
                not isinstance(path, str)
                or not isinstance(sha, str)
                or isinstance(size, bool)
                or not isinstance(size, int)
                or size < 0
            ):
                raise RepositoryIngestionError(
                    502, "GitHub returned invalid file metadata"
                )
            full_path = f"{prefix}/{path}".lstrip("/") if prefix else path
            if should_include_file(full_path):
                files.append(TreeFile(path=full_path, sha=sha, size=size))
        return files

    async def _get_json(
        self,
        client: httpx.AsyncClient,
        api_path: str,
    ) -> dict[str, object]:
        _, payload = await self._get_response_json(
            client, f"{GITHUB_API_URL}{api_path}"
        )
        return payload

    async def _get_response_json(
        self,
        client: httpx.AsyncClient,
        url: str,
    ) -> tuple[httpx.Response, dict[str, object]]:
        try:
            response = await client.get(url)
        except httpx.TimeoutException as error:
            raise RepositoryIngestionError(
                504, "GitHub API request timed out"
            ) from error
        except httpx.RequestError as error:
            raise RepositoryIngestionError(
                502, "Unable to reach the GitHub API"
            ) from error

        if response.status_code == 404:
            raise RepositoryIngestionError(404, "Public repository not found")
        if response.status_code == 429 or (
            response.status_code == 403
            and (
                response.headers.get("X-RateLimit-Remaining") == "0"
                or response.headers.get("Retry-After") is not None
                or self._is_rate_limit_response(response)
            )
        ):
            raise RepositoryIngestionError(
                429, "GitHub API rate limit exceeded"
            )
        if response.status_code >= 400:
            raise RepositoryIngestionError(
                502, "GitHub API returned an error"
            )

        try:
            payload = response.json()
        except ValueError as error:
            raise RepositoryIngestionError(
                502, "GitHub API returned invalid JSON"
            ) from error
        if not isinstance(payload, dict):
            raise RepositoryIngestionError(
                502, "GitHub API returned an invalid response"
            )
        return response, payload

    @staticmethod
    def _is_rate_limit_response(response: httpx.Response) -> bool:
        try:
            payload = response.json()
        except ValueError:
            return False
        message = payload.get("message") if isinstance(payload, dict) else None
        return isinstance(message, str) and "rate limit" in message.lower()

    @staticmethod
    def _decode_blob(
        blob: dict[str, object],
        expected_size: int,
    ) -> bytes:
        if blob.get("encoding") != "base64" or not isinstance(
            blob.get("content"), str
        ):
            raise RepositoryIngestionError(
                502, "GitHub returned an unsupported file encoding"
            )
        try:
            encoded_content = "".join(blob["content"].split())
            decoded = base64.b64decode(encoded_content, validate=True)
        except (binascii.Error, ValueError) as error:
            raise RepositoryIngestionError(
                502, "GitHub returned invalid file content"
            ) from error
        if len(decoded) != expected_size:
            raise RepositoryIngestionError(
                502, "GitHub returned a file with an unexpected size"
            )
        return decoded
